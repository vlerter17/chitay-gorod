// ===== SVG-ЗАГЛУШКА (работает без интернета) =====
function makeSvgCover(title, author, idx) {
    const palettes = [
        ['#667eea', '#764ba2'], ['#f093fb', '#f5576c'],
        ['#4facfe', '#00f2fe'], ['#11998e', '#38ef7d'],
        ['#e8d5b7', '#c9a961'], ['#f59e0b', '#d97706'],
        ['#8b5cf6', '#6366f1'], ['#ec4899', '#be185d']
    ];
    const [c1, c2] = palettes[Math.abs(idx) % palettes.length];
    const esc = s => String(s).replace(/[&<>"']/g, ch => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&apos;'}[ch]));

    const words = String(title).split(' ');
    const lines = [];
    let cur = '';
    words.forEach(w => {
        if ((cur + ' ' + w).trim().length > 16) {
            if (cur) lines.push(cur);
            cur = w;
        } else {
            cur = cur ? cur + ' ' + w : w;
        }
    });
    if (cur) lines.push(cur);

    const startY = 260 - (lines.length - 1) * 16;
    const titleSvg = lines.map((line, i) =>
        `<text x="200" y="${startY + i * 34}" font-family="Georgia, serif" font-size="26" fill="#fff" text-anchor="middle" font-weight="bold">${esc(line)}</text>`
    ).join('');
    const afterTitle = startY + lines.length * 34;

    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="400" height="600" viewBox="0 0 400 600">
        <defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
            <stop offset="0%" stop-color="${c1}"/><stop offset="100%" stop-color="${c2}"/>
        </linearGradient></defs>
        <rect width="400" height="600" fill="url(#g)"/>
        <rect x="15" y="15" width="370" height="570" fill="none" stroke="rgba(255,255,255,0.3)" stroke-width="2"/>
        <rect x="25" y="25" width="350" height="550" fill="none" stroke="rgba(255,255,255,0.15)" stroke-width="1"/>
        ${titleSvg}
        <line x1="120" y1="${afterTitle + 6}" x2="280" y2="${afterTitle + 6}" stroke="rgba(255,255,255,0.4)" stroke-width="1"/>
        <text x="200" y="${afterTitle + 36}" font-family="Georgia, serif" font-size="14" fill="rgba(255,255,255,0.85)" text-anchor="middle">${esc(author)}</text>
        <text x="200" y="555" font-family="Georgia, serif" font-size="11" fill="rgba(255,255,255,0.55)" text-anchor="middle" letter-spacing="3">ЧИТАЙ-ГОРОД</text>
    </svg>`;
    return 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(svg);
}

function attachCover(imgEl, book, idx) {
    if (!imgEl || !book) return;
    imgEl.onerror = () => {
        imgEl.onerror = null;
        imgEl.src = makeSvgCover(book.title, book.author, idx);
    };
    imgEl.src = book.image;
}